import assert from "node:assert/strict";
import { buildLiveStudentRoster, livePresenceStatus, isLivePresenceRecent } from "../../shared/liveQuizPresence.mjs";
const now=1700000000000;
const fresh=extra=>({ultimo_ping:now-1000,pregunta_vista:1,ha_respondido:false,ubicacion:"prueba",...extra});
const session={estado:"en_pregunta",pregunta_actual_idx:1};
assert.equal(isLivePresenceRecent({},now),false);
assert.equal(isLivePresenceRecent({ultimo_ping:"bad"},now),false);
assert.equal(isLivePresenceRecent({ultimo_ping:now+50000},now),false);
assert.equal(isLivePresenceRecent({ultimo_ping:now-15000},now),false);
assert.equal(isLivePresenceRecent({ultimo_ping:now-14999},now),true);
assert.equal(livePresenceStatus(fresh({pregunta_vista:-1,ubicacion:"portal"}),session,now).label,"En el portal");
assert.equal(livePresenceStatus(fresh({ha_respondido:true,pregunta_vista:0}),session,now).answered,false,"La respuesta anterior no cuenta para la pregunta nueva");
assert.equal(livePresenceStatus(fresh({ha_respondido:true}),session,now).answered,true);
assert.equal(livePresenceStatus(fresh({ubicacion:"aviso"}),session,now).label,"Aviso de falta");
assert.equal(livePresenceStatus(fresh(),{...session,estado:"lobby"},now).label,"En sala");
assert.equal(livePresenceStatus(fresh(),{...session,estado:"esperando_siguiente"},now).label,"Sin respuesta");
assert.equal(livePresenceStatus(fresh(),session,now,{estado:"borrador",updated_at:new Date(now).toISOString()}).label,"Habilitada de nuevo","No reutiliza conexiones previas a la reapertura");
assert.equal(livePresenceStatus(fresh(),session,now,{estado:"borrador",updated_at:new Date(now-2000).toISOString()}).label,"Respondiendo");
assert.equal(livePresenceStatus(fresh({ha_respondido:true}),session,now,{estado:"calificado"}).label,"Entregó");
const enrolled=[{numero_cuenta:" A ",nombre_completo:"A"},{numero_cuenta:"A",nombre_completo:"A"},{numero_cuenta:"B"},{numero_cuenta:"C"},{numero_cuenta:"X",activo:false},{numero_cuenta:""}];
const live={...session,alumnos_conectados:{A:fresh({ha_respondido:true}),B:fresh({ultimo_ping:now-30000}),C:fresh(),ghost:fresh(),makeup:fresh({reposicion:{origen:"B"}})},entregas_estudiantes:{C:{estado:"enviado"}}};
let roster=buildLiveStudentRoster(enrolled,live,now);
assert.equal(roster.enrolledCount,3);assert.equal(roster.invitedCount,1);assert.equal(roster.connectedCount,2);assert.equal(roster.answeredCount,1);
assert.equal(roster.students.find(row=>row.key==="C").label,"Entregó");
assert.equal(roster.students.some(row=>row.key==="ghost"),false,"Contador y listado usan los mismos estudiantes");
roster=buildLiveStudentRoster(enrolled,live,now+16000);
assert.equal(roster.connectedCount,0);assert.equal(roster.students.find(row=>row.key==="C").label,"Entregó");
roster=buildLiveStudentRoster(enrolled,live,now,false);
assert(roster.students.every(row=>row.label==="Sin verificar"));
console.log("PASS presencia: portal/prueba/aviso/entrega, pregunta vigente, señales vencidas o inválidas, matrícula sin duplicados, reposición y errores sin estados inventados.");
