import assert from "node:assert/strict";
import vm from "node:vm";
import { createRequire } from "node:module";
import { build } from "esbuild";
import { getMakeupOutcome, makeupAttendanceOutcome } from "../../shared/studentMakeups.mjs";
const require=createRequire(import.meta.url);
const ExcelJS=require("exceljs");
let download;
const output=await build({entryPoints:["client/src/utils/exportExcel.js"],bundle:true,platform:"node",format:"cjs",write:false,external:["exceljs"]});
const module={exports:{}};
vm.runInNewContext(output.outputFiles[0].text,{module,exports:module.exports,require,console,Blob,window:{URL:{createObjectURL(blob){download=blob;return "blob:isolated";},revokeObjectURL(){}}},document:{createElement(){return {click(){}};},body:{appendChild(){},removeChild(){}}}});
const attendances={asistencia_1:"Falta justificada",asistencia_2:"Falta justificada",asistencia_3:"Falta justificada",reposicion_1:"Repuso",reposicion_2:"No repuso"};
const snapshot=JSON.stringify(attendances);
assert.equal(makeupAttendanceOutcome("Asistio"),"Repuso");assert.equal(makeupAttendanceOutcome("Falta injustificada"),"No repuso");assert.equal(makeupAttendanceOutcome(null),null);
assert.equal(getMakeupOutcome(attendances,3),null);
await module.exports.exportStyledExcel({viewType:"asistencia",seccion:{codigo:"DEMO",carrera:"Medicina"},estudiantes:[{numero_cuenta:"DEMO",nombre_completo:"Alumno aislado",asistencias:attendances,notas:{}}],currentParcialConfig:{label:"I Parcial",semanas:[1,2,3],semanasAsistencia:[1,2,3],asistenciasExamenes:[]},selectedParcial:"I"});
const workbook=new ExcelJS.Workbook();await workbook.xlsx.load(await download.arrayBuffer());
const cells=[];workbook.worksheets[0].eachRow(row=>row.eachCell(cell=>cells.push(cell)));
assert(cells.some(cell=>cell.value==="FJ\nRepuso"));assert(cells.some(cell=>cell.value==="FJ\nNo repuso"));assert(cells.some(cell=>cell.value==="FJ"));
assert(cells.filter(cell=>String(cell.value).startsWith("FJ\n")).every(cell=>cell.alignment.wrapText));
assert.equal(JSON.stringify(attendances),snapshot);
console.log("PASS: exportación conserva FJ y añade Repuso/No repuso; el estado sin lista no se convierte en falta; etiquetas y asistencia original intactas.");
